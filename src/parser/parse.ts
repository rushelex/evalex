import type { AstNode } from './ast';

import { parse as peggyParse, SyntaxError } from './grammar/__generated__/grammar';

function buildErrorWithLocation(error: SyntaxError) {
  const message = `${error.message.endsWith('.') ? error.message : `${error.message}.`}`;

  return new SyntaxError(
    `${message} [${error.location.start.offset},${error.location.end.offset}]`,
    error.expected,
    error.found ?? null,
    error.location,
  );
}

/**
 * Parses a formula string into an AST.
 *
 * @param formula Formula string to parse.
 * @returns Root of the AST tree of type AstNode.
 * @throws SyntaxError if the formula is invalid.
 */
export function parse(formula: string): AstNode {
  try {
    // PEG.js parser may return 'any' or untyped objects.
    // We cast the result to AstNode, assuming the structure,
    // generated by your grammar.pegjs (using nodes.ts in grammar actions),
    // is compatible with the AstNode interface.
    // eslint-disable-next-line ts/no-unsafe-assignment
    const parsedNode = peggyParse(formula);
    return parsedNode as AstNode;
  }
  catch (error) {
    if (error instanceof SyntaxError) {
      throw buildErrorWithLocation(error);
    }

    throw error;
  }
}
